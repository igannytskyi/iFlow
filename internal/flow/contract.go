// stubFile is the name of the file a package the change creates is given,
// from the contract, while the tests written before it are vetted. It is
// handed to the compiler as an overlay and never written in the workspace.
const stubFile = "iflow_contract_stub.go"

// contractOverlay makes, for every package a code unit creates that does
// not exist in ws yet, a file holding what the units' contract says it
// provides — each function with an empty body — and returns the compiler's
// -overlay argument naming them, with a function that removes them. Tests
// written first import a package before it exists; without it, the
// compiler stops at the import and says nothing of what else the tests got
// wrong — a name they misspell, a value they miscount. With it, it says all.
// Where nothing is to be made, the argument is empty.
func (r *Run) contractOverlay(ws string) (string, func()) {
	byDir := map[string][]string{}
	for _, u := range r.units {
		if u.tests {
			continue
		}
		dirs := map[string]bool{}
		for _, p := range u.scope {
			if strings.HasSuffix(p, ".go") && !strings.HasSuffix(p, "_test.go") {
				dirs[filepath.ToSlash(filepath.Dir(p))] = true
			}
		}
		if len(dirs) != 1 {
			continue // which package each name is in would be a guess
		}
		for dir := range dirs {
			if !hasCode(filepath.Join(ws, dir)) {
				byDir[dir] = append(byDir[dir], u.provides...)
			}
		}
	}
	if len(byDir) == 0 {
		return "", func() {}
	}
	tmp, err := os.MkdirTemp("", "iflow-contract-")
	if err != nil {
		return "", func() {}
	}
	done := func() { os.RemoveAll(tmp) }
	replace := map[string]string{}
	for dir, provides := range byDir {
		src := stubOf(filepath.Base(dir), provides)
		if src == "" {
			continue
		}
		at := filepath.Join(tmp, strings.ReplaceAll(dir, "/", "_")+".go")
		if os.WriteFile(at, []byte(src), 0o644) != nil {
			continue
		}
		replace[filepath.Join(ws, dir, stubFile)] = at
	}
	if len(replace) == 0 {
		done()
		return "", func() {}
	}
	b, _ := json.Marshal(map[string]any{"Replace": replace})
	overlay := filepath.Join(tmp, "overlay.json")
	if os.WriteFile(overlay, b, 0o644) != nil {
		done()
		return "", func() {}
	}
	return "-overlay=" + overlay, done
}

// hasCode reports whether dir holds a Go file other than a test.
func hasCode(dir string) bool {
	entries, _ := os.ReadDir(dir)
	return slices.ContainsFunc(entries, func(e os.DirEntry) bool {
		n := e.Name()
		return !e.IsDir() && strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go")
	})
}

// stubOf is a Go file of package pkg declaring what the contract says it
// provides: each declaration the contract states in Go, a function given a
// body that panics; what is said in prose is left out. Empty when nothing
// in it is Go.
func stubOf(pkg string, provides []string) string {
	var decls []string
	for _, p := range provides {
		d := strings.TrimSpace(p)
		if i := strings.Index(d, " — "); i > 0 {
			d = strings.TrimSpace(d[:i]) // the declaration, before what is said of it
		}
		if strings.HasPrefix(d, "func ") {
			d += ` { panic("the contract's stub") }`
		}
		if !strings.HasPrefix(d, "func ") && !strings.HasPrefix(d, "type ") {
			continue
		}
		if _, err := parser.ParseFile(token.NewFileSet(), "", "package p\n"+d, 0); err != nil {
			continue
		}
		decls = append(decls, d)
	}
	if len(decls) == 0 {
		return ""
	}
	body := strings.Join(decls, "\n\n")
	var imports []string
	for _, m := range qualified.FindAllStringSubmatch(body, -1) {
		if path, ok := stdlib[m[1]]; ok && !slices.Contains(imports, path) {
			imports = append(imports, path)
		}
	}
	src := "// Code generated by iFlow from the units' contract, to vet the tests written before it. DO NOT EDIT.\n\npackage " + pkg + "\n\n"
	if len(imports) > 0 {
		slices.Sort(imports)
		src += "import (\n\t\"" + strings.Join(imports, "\"\n\t\"") + "\"\n)\n\n"
	}
	return src + body + "\n"
}

var qualified = regexp.MustCompile(`\b([a-z][a-z0-9]*)\.[A-Z]\w*`)

// stdlib is the import path of the standard packages a contract names most.
var stdlib = map[string]string{
	"bytes": "bytes", "context": "context", "errors": "errors", "fmt": "fmt", "io": "io",
	"os": "os", "strings": "strings", "sync": "sync", "time": "time", "http": "net/http",
	"url": "net/url", "json": "encoding/json", "image": "image", "color": "image/color",
	"fs": "io/fs", "exec": "os/exec", "regexp": "regexp", "sql": "database/sql", "slog": "log/slog",
}

// providedNames is the names a unit's contract says it gives the others,
// each as the code declares it: the function, method or type, the variable
// or constant, the field. What is said in prose names nothing.
func providedNames(provides []string) []string {
	var out []string
	for _, p := range provides {
		if m := declared.FindStringSubmatch(strings.TrimSpace(p)); m != nil {
			for _, name := range m[1:] {
				if name != "" && !slices.Contains(out, name) {
					out = append(out, name)
				}
			}
		}
	}
	return out
}

// declared is the name a line of a contract declares: "func (u *UI) quiet()",
// "func New(", "type Sender", "var lookPath", "field Notify notify.Sender".
var declared = regexp.MustCompile(`^(?:func\s+(?:\([^)]*\)\s*)?(\w+)\s*\(|(?:type|var|const)\s+(\w+)\b|field\s+(\w+)\b|def\s+(\w+)\s*\(|class\s+(\w+)\b)`)

// estateGraph answers an agent's questions of the estate's model of its
// code, each place with its line as the estate holds it.
type estateGraph struct {
	repo *estate.Repo
	root string
}

// Defined is where name is defined, each with its first line.
func (g estateGraph) Defined(name string) (string, error) {
	places, err := g.repo.WhereDefined(name)
	if err != nil {
		return "", err
	}
	if len(places) == 0 {
		return name + " is defined nowhere in the estate as it stood; an earlier unit may provide it — see what you were handed", nil
	}
	var b strings.Builder
	for _, p := range places[:min(len(places), 12)] {
		fmt.Fprintf(&b, "%s:%d-%d  %s\n", p.File, p.Start, p.End, g.line(p.File, p.Start))
	}
	return b.String(), nil
}

// Callers is every place that uses name, firmest first, each with its line.
func (g estateGraph) Callers(name string) (string, error) {
	sites, err := g.repo.CallSites(name)
	if err != nil {
		return "", err
	}
	if len(sites) == 0 {
		return "nothing in the estate uses " + name, nil
	}
	var b strings.Builder
	for _, s := range sites[:min(len(sites), 40)] {
		fmt.Fprintf(&b, "%s:%d  %s\n", s.File, s.Line, g.line(s.File, s.Line))
	}
	if len(sites) > 40 {
		fmt.Fprintf(&b, "[%d more]\n", len(sites)-40)
	}
	return b.String(), nil
}

func (g estateGraph) line(file string, n int) string {
	b, err := os.ReadFile(filepath.Join(g.root, filepath.FromSlash(file)))
	if err != nil {
		return ""
	}
	lines := strings.Split(string(b), "\n")
	if n < 1 || n > len(lines) {
		return ""
	}
	return strings.TrimSpace(lines[n-1])
}
