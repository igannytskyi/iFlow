// outsideNames are not the estate. A boundary nobody draws includes whatever
// happens to be on disk: libraries installed beside the code, build output,
// changes still in flight that hold copies of the source.
var outsideNames = map[string]bool{
	".git": true, "__pycache__": true, "node_modules": true, ".claude": true,
	".venv": true, "venv": true, "dist": true, "build": true, "changes": true,
	"_lib": true, "vendor": true, "third_party": true, "site-packages": true,
}

// Unreadable are extensions known to be code. A file of one nothing here
// reads is counted as unseen: a zero over ground nobody looked at reads
// exactly like a zero over ground that was covered.
var Unreadable = map[string]bool{
	".ts": true, ".tsx": true, ".js": true, ".jsx": true, ".go": true, ".rs": true,
	".java": true, ".kt": true, ".rb": true, ".php": true, ".cs": true, ".c": true,
	".h": true, ".cpp": true, ".swift": true, ".scala": true, ".ex": true, ".exs": true,
}

// isOutside reports whether a path inside the estate is outside what is
// looked at. Only the parts inside the estate are matched: an estate kept
// under a directory called changes is not a folder of changes.
func isOutside(rel string) bool {
	for part := range strings.SplitSeq(rel, "/") {
		if outsideNames[part] || strings.HasPrefix(part, "_bmad") {
			return true
		}
	}
	return false
}

// Ground nobody wrote. A generated file is real code and not the estate's
// code: nobody edits it, and a change to it is a change to whatever produced
// it. It is skipped and counted, never skipped and forgotten.
var (
	generatedNames  = []string{".pb.go", "_pb2.py", "_pb2_grpc.py", ".g.dart", ".generated.", ".designer.cs", ".freezed.dart", "_generated.go", ".pb.cc", ".pb.h", "parser.c"}
	generatedBanner = regexp.MustCompile(`(?i)(@generated|code generated by|autogenerated|auto-generated|automatically generated|do not edit|generated by the protocol buffer)`)
)

func isGenerated(abs string) bool {
	name := filepath.Base(abs)
	for _, mark := range generatedNames {
		if strings.Contains(name, mark) {
			return true
		}
	}
	f, err := os.Open(abs)
	if err != nil {
		return false
	}
	defer f.Close()
	head := make([]byte, 2400) // 600 characters, at most four bytes each
	n, _ := f.Read(head)
	runes := []rune(string(head[:n]))
	return generatedBanner.MatchString(string(runes[:min(len(runes), 600)]))
}

// file is one file of the estate and what is known about it without reading
// it through a reader.
type file struct {
	rel       string
	abs       string
	readable  bool
	generated bool
}

// Repo is one repository of the estate, as it stands on disk now.
type Repo struct {
	Root string

	walk    sync.Once
	files   []file
	history sync.Once
	touched map[string][2]string

	indexOnce sync.Once
	index     *Index
	indexErr  error

	graphOnce sync.Once
	edges     map[string]map[string]bool
	firm      map[string]map[string]bool

	// base is the repository this one is a copy of, with some files
	// changed: what it derived of a file holding the same is not derived
	// again.
	base *Repo
}

// Over is the repository at root, a copy of this one with some files
// changed or added — the copy one piece of work is carried in. Only what
// differs from this one is read; nothing derived of it is kept.
func (r *Repo) Over(root string) *Repo {
	o := Open(root)
	o.base = r
	return o
}

// Open returns the repository at root. Nothing is read until it is asked.
func Open(root string) *Repo {
	abs, err := filepath.Abs(root)
	if err == nil {
		if real, err := filepath.EvalSymlinks(abs); err == nil {
			abs = real
		}
		root = abs
	}
	return &Repo{Root: root}
}

// all is every file under the root that is not outside it, in path order.
func (r *Repo) all() []file {
	r.walk.Do(func() {
		_ = filepath.WalkDir(r.Root, func(p string, d fs.DirEntry, err error) error {
			if err != nil || p == r.Root {
				return nil
			}
			rel, _ := filepath.Rel(r.Root, p)
			rel = filepath.ToSlash(rel)
			if d.IsDir() {
				if outsideNames[d.Name()] || strings.HasPrefix(d.Name(), "_bmad") {
					return filepath.SkipDir
				}
				return nil
			}
			if isOutside(rel) {
				return nil
			}
			if d.Type()&fs.ModeSymlink != 0 {
				if st, err := os.Stat(p); err != nil || !st.Mode().IsRegular() {
					return nil
				}
			} else if !d.Type().IsRegular() {
				return nil
			}
			f := file{rel: rel, abs: p, readable: reader.Readable(p)}
			if f.readable {
				f.generated = isGenerated(p)
			}
			r.files = append(r.files, f)
			return nil
		})
	})
	return r.files
}

// Sources is every file some reader here can read and nobody generated, by
// path relative to the root, in path order.
func (r *Repo) Sources() []string {
	var out []string
	for _, f := range r.all() {
		if f.readable && !f.generated {
			out = append(out, f.rel)
		}
	}
	return out
}

func (r *Repo) abs(rel string) string { return filepath.Join(r.Root, filepath.FromSlash(rel)) }

// Unseen counts, by extension, the files here in a language known to be
// code and read by nothing installed.
func (r *Repo) Unseen() map[string]int {
	out := map[string]int{}
	for _, f := range r.all() {
		ext := path.Ext(f.rel)
		if Unreadable[ext] && !reader.Claims(ext) {
			out[ext]++
		}
	}
	return out
}

// unreadSources is every file in a language known to be code and read by
// nothing here.
func (r *Repo) unreadSources() []string {
	var out []string
	for _, f := range r.all() {
		if ext := path.Ext(f.rel); Unreadable[ext] && !reader.Claims(ext) {
			out = append(out, f.rel)
		}
	}
	return out
}

// MachineWritten counts files here written by something other than a person.
func (r *Repo) MachineWritten() int {
	n := 0
	for _, f := range r.all() {
		if f.readable && f.generated {
			n++
		}
	}
	return n
}

// history is one walk of a repository's history: path → the commit that last
// moved it and when. One walk answers for every file; asking once per file
// cost a process each.
func history(dir, prefix string) map[string][2]string {
	out, err := exec.Command("git", "-C", dir, "log", "--format=@%h %cs", "--name-only", "--no-merges").Output()
	seen := map[string][2]string{}
	if err != nil {
		return seen
	}
	commit, when := "unversioned", ""
	sc := bufio.NewScanner(bytes.NewReader(out))
	sc.Buffer(make([]byte, 1<<16), 1<<24)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "@") {
			parts := append(strings.Fields(line[1:]), "", "")
			commit, when = parts[0], parts[1]
			continue
		}
		if strings.TrimSpace(line) != "" {
			if _, ok := seen[prefix+line]; !ok {
				seen[prefix+line] = [2]string{commit, when}
			}
		}
	}
	return seen
}

// lastTouched is the commit that last moved a file, across every repository
// under the root: an estate of nine services is nine repositories in one
// directory that is not itself one.
func (r *Repo) lastTouched(rel string) (string, string) {
	r.history.Do(func() {
		r.touched = history(r.Root, "")
		if len(r.touched) > 0 {
			return
		}
		entries, _ := os.ReadDir(r.Root)
		sort.Slice(entries, func(i, j int) bool { return entries[i].Name() < entries[j].Name() })
		for _, e := range entries {
			if e.IsDir() {
				if _, err := os.Stat(filepath.Join(r.Root, e.Name(), ".git")); err == nil {
					for k, v := range history(filepath.Join(r.Root, e.Name()), e.Name()+"/") {
						r.touched[k] = v
					}
				}
			}
		}
	})
	if v, ok := r.touched[rel]; ok {
		return v[0], v[1]
	}
	return "unversioned", ""
}

// Stamp is what a file was derived from, in a form that changes when it
// does: its contents always, and the commit that last moved it where history
// covers it. A file edited and not committed is still at its last commit, so
// a stamp of the commit alone would serve the file as it used to be.
func (r *Repo) Stamp(rel string) (stamp, when string) {
	b, err := os.ReadFile(r.abs(rel))
	if err != nil {
		return "unversioned", ""
	}
	return r.stamp(rel, digestOf(b))
}

func (r *Repo) stamp(rel, digest string) (stamp, when string) {
	commit, when := r.lastTouched(rel)
	if commit != "unversioned" {
		return commit + "+" + digest, when
	}
	return "contents:" + digest, when
}

// digestOf is a file's contents, short.
func digestOf(b []byte) string {
	sum := sha1.Sum(b)
	return hex.EncodeToString(sum[:])[:12]
}

// Head is the commit the repository is at, or "unversioned".
func (r *Repo) Head() string {
	out, err := exec.Command("git", "-C", r.Root, "rev-parse", "--short", "HEAD").Output()
	if s := strings.TrimSpace(string(out)); err == nil && s != "" {
		return s
	}
	return "unversioned"
}

// Home is where material derived for this repository is kept: beside it by
// default, or, where IFLOW_ESTATE names a directory, in a cache there per
// repository.
func (r *Repo) Home() string {
	base := os.Getenv("IFLOW_ESTATE")
	if base == "" {
		return filepath.Join(r.Root, ".estate")
	}
	if abs, err := filepath.Abs(expandHome(base)); err == nil {
		base = abs
	}
	// Named by where it sits under IFLOW_ESTATE_ROOT — the working directory
	// when that is not set — and by its own name when it sits elsewhere.
	name := filepath.Base(r.Root)
	here := os.Getenv("IFLOW_ESTATE_ROOT")
	if here == "" {
		here = "."
	}
	if abs, err := filepath.Abs(expandHome(here)); err == nil {
		if real, err := filepath.EvalSymlinks(abs); err == nil {
			abs = real
		}
		if rel, err := filepath.Rel(abs, r.Root); err == nil && rel != ".." && !strings.HasPrefix(rel, "../") {
			name = filepath.ToSlash(rel)
		}
	}
	return filepath.Join(base, "cache", name)
}

func expandHome(p string) string {
	if strings.HasPrefix(p, "~/") {
		if h, err := os.UserHomeDir(); err == nil {
			return filepath.Join(h, p[2:])
		}
	}
	return p
}
